class SourcePackage(NamedTuple):
    name: str            # MSYS2 package base name
    version: str         # pkgver-pkgrel
    size: int            # archive size in bytes
    sha256: str          # archive SHA-256 (lower case)
    sig_sha256: str      # detached signature SHA-256 (lower case)

    @property
    def archive(self) -> str:
        return f"{self.name}-{self.version}.src.tar.zst"

    @property
    def signature(self) -> str:
        return self.archive + ".sig"


