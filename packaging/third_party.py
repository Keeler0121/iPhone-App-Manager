def python_runtime_mismatches() -> list[str]:
    """Differences between the running Python build and the versions this module documents (empty = none)."""
    out: list[str] = []

    def check(label: str, found: str, expected: str) -> None:
        if found != expected:
            out.append(f"{label}: found {found}, notices document {expected}")

    check("Python", ".".join(map(str, sys.version_info[:3])), PYTHON_PINS["python"])
    import ssl
    check("OpenSSL (Python)", ssl.OPENSSL_VERSION.split()[1], PYTHON_PINS["openssl"])
    import pyexpat
    check("Expat", pyexpat.EXPAT_VERSION.replace("expat_", ""), PYTHON_PINS["expat"])
    import zlib
    check("zlib (Python)", zlib.ZLIB_RUNTIME_VERSION, PYTHON_PINS["zlib"])
    import _decimal
    check("libmpdec", _decimal.__libmpdec_version__, PYTHON_PINS["libmpdec"])
    import tkinter
    check("Tcl/Tk", str(tkinter.Tcl().call("info", "patchlevel")), PYTHON_PINS["tcl"])
    return out


def pyinstaller_mismatch() -> str | None:
    try:
        from importlib.metadata import version
        found = version("pyinstaller")
    except Exception as exc:                                  # not installed in this environment
        return f"PyInstaller version could not be read ({exc})"
    return None if found == PYTHON_PINS["pyinstaller"] else f"PyInstaller: found {found}, notices document {PYTHON_PINS['pyinstaller']}"


