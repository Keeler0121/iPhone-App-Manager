def load_licence_manifest() -> dict:
    return json.loads((LICENCES_DIR / "manifest.json").read_text(encoding="utf-8"))


def licence_file_names() -> list[str]:
    return sorted(load_licence_manifest())


def verify_licence_files() -> list[str]:
    """Problems found with the committed licence files (hash/size mismatch, missing or unexpected files)."""
    problems = []
    manifest = load_licence_manifest()
    for name, info in sorted(manifest.items()):
        path = LICENCES_DIR / name
        if not path.is_file():
            problems.append(f"missing: {name}")
            continue
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != info["sha256"] or len(data) != info["size"]:
            problems.append(f"changed: {name}")
    on_disk = {p.name for p in LICENCES_DIR.iterdir() if p.is_file()} - {"manifest.json"}
    for extra in sorted(on_disk - set(manifest)):
        problems.append(f"not in manifest: {extra}")
    return problems


